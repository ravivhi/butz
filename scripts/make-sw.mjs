// Writes <dist>/sw.js: an offline service worker that precaches the whole web export.
// Usage: node scripts/make-sw.mjs dist   (run after `expo export -p web`; `npm run build:web` does both)
//
// The cache name comes from a hash of every file, so each deploy installs a fresh cache and deletes the old one.
// Pages (navigations) are network-first so a new version shows up on the next launch when online; everything else
// (hashed JS bundle, fonts, images, sounds) is cache-first.
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, relative, resolve, sep } from 'node:path';

const dist = resolve(process.argv[2] ?? 'dist');
const files = readdirSync(dist, { recursive: true, withFileTypes: true })
  .filter((d) => d.isFile())
  .map((d) => relative(dist, join(d.parentPath, d.name)).split(sep).join('/'))
  .filter((f) => f !== 'sw.js' && !f.endsWith('.map'))
  .sort();
const hash = createHash('sha256');
for (const f of files) hash.update(f).update('\0').update(readFileSync(join(dist, f)));
const cache = `butz-${hash.digest('hex').slice(0, 12)}`;
const urls = ['./', ...files.map((f) => encodeURI(f))];

writeFileSync(join(dist, 'sw.js'), `// Generated by scripts/make-sw.mjs. Do not edit.
const CACHE = ${JSON.stringify(cache)};
const FILES = ${JSON.stringify(urls, null, 0)};

self.addEventListener('install', (e) => {
  self.skipWaiting();
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)));
});

self.addEventListener('activate', (e) => {
  e.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('butz-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

// Network first for pages (3 s timeout, then the cached copy), cache first for the rest.
async function page(req) {
  const cache = await caches.open(CACHE);
  try {
    const res = await Promise.race([
      fetch(req),
      new Promise((_, reject) => setTimeout(() => reject(new Error('timeout')), 3000)),
    ]);
    if (res.ok) return res;
  } catch {}
  return (await cache.match(req, { ignoreSearch: true })) || (await cache.match('./')) || fetch(req);
}

self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== self.location.origin) return;
  if (req.mode === 'navigate') { e.respondWith(page(req)); return; }
  e.respondWith(caches.match(req, { ignoreSearch: true }).then((hit) => hit || fetch(req)));
});
`);
console.log(`sw.js: ${cache}, ${urls.length} files`);
