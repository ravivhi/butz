/* Neural Hebrew audio for every line the app can say (SPEC R-T4), with the official Azure AI Speech REST API.
   Setup (once): create a free "Speech" resource in the Azure portal, then either set AZURE_SPEECH_KEY + AZURE_SPEECH_REGION
   or create .secrets/azure-speech.json = {"key": "…", "region": "westeurope"} (git-ignored). Then: npm run audio.
   Incremental: files that exist are kept, so a rerun only adds new or changed lines. Writes assets/audio/<hash>.mp3,
   src/services/clips.generated.ts (the app plays these instead of the device voice) and test-results/audio-review.html.
   Options: --dry (count only, no key needed)  --limit N  --voice he-IL-HilaNeural  --prune (delete unused files). */
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, readdirSync, unlinkSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { allSpokenTexts, type Spoken } from '../src/engine/spoken.ts';
import { speakable } from '../src/engine/phrases.ts';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const argv = process.argv.slice(2);
const opt = (name: string): string | undefined => { const i = argv.indexOf('--' + name); return i >= 0 ? argv[i + 1] : undefined; };
const flag = (name: string): boolean => argv.includes('--' + name);

const VOICE = opt('voice') ?? process.env.AZURE_SPEECH_VOICE ?? 'he-IL-AvriNeural';
const RATE: Record<Spoken['kind'], string> = { sound: '-12%', word: '-8%', talk: '-4%' };
const FORMAT = 'audio-24khz-48kbitrate-mono-mp3';
const AUDIO_DIR = join(root, 'assets', 'audio');
const WORKERS = 3;

const fileOf = (s: Spoken): string => createHash('sha1').update(`${VOICE}|${RATE[s.kind]}|${s.text}`).digest('hex').slice(0, 16) + '.mp3';
const xml = (t: string): string => t.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const ssml = (s: Spoken): string =>
  `<speak version="1.0" xmlns="http://www.w3.org/2001/10/synthesis" xml:lang="he-IL"><voice name="${VOICE}">` +
  `<prosody rate="${RATE[s.kind]}">${xml(speakable(s.text))}</prosody></voice></speak>`;

function credentials(): { key?: string; region?: string } {
  let key = process.env.AZURE_SPEECH_KEY;
  let region = process.env.AZURE_SPEECH_REGION;
  const f = join(root, '.secrets', 'azure-speech.json');
  if ((!key || !region) && existsSync(f)) {
    const j = JSON.parse(readFileSync(f, 'utf8')) as { key?: string; region?: string };
    key ??= j.key;
    region ??= j.region;
  }
  return { key, region };
}

const sleep = (ms: number) => new Promise((r) => setTimeout(r, ms));

async function synth(url: string, key: string, body: string, attempt = 0): Promise<Buffer> {
  const res = await fetch(url, {
    method: 'POST',
    headers: { 'Ocp-Apim-Subscription-Key': key, 'Content-Type': 'application/ssml+xml', 'X-Microsoft-OutputFormat': FORMAT, 'User-Agent': 'butz-hebrew-reading' },
    body,
  });
  if (res.status === 429 || res.status >= 500) {
    if (attempt >= 10) throw new Error(`HTTP ${res.status} after ${attempt} retries`);
    const wait = Number(res.headers.get('retry-after') ?? 0) * 1000 || Math.min(60_000, 1500 * 2 ** attempt);
    await sleep(wait);
    return synth(url, key, body, attempt + 1);
  }
  if (!res.ok) throw new Error(`HTTP ${res.status}: ${(await res.text()).slice(0, 200)}`);
  return Buffer.from(await res.arrayBuffer());
}

function writeOutputs(all: Spoken[]): number {
  const have = all.filter((s) => existsSync(join(AUDIO_DIR, fileOf(s))));
  const lines = have.map((s) => `  ${JSON.stringify(s.text)}: require('../../assets/audio/${fileOf(s)}'),`);
  writeFileSync(join(root, 'src', 'services', 'clips.generated.ts'),
    `/* Generated by scripts/make-audio.ts (npm run audio) with ${VOICE}. Do not edit: rerun the script instead. */\n` +
    `export const GENERATED: Record<string, number> = {\n${lines.join('\n')}\n};\n`);
  mkdirSync(join(root, 'test-results'), { recursive: true });
  const rows = have.map((s) => `<tr><td>${s.kind}</td><td dir="rtl">${xml(s.text)}</td><td><audio controls preload="none" src="../assets/audio/${fileOf(s)}"></audio></td></tr>`);
  writeFileSync(join(root, 'test-results', 'audio-review.html'),
    `<!doctype html><meta charset="utf-8"><title>Butz audio review</title><style>body{font-family:sans-serif}td{padding:4px 10px;font-size:22px}</style>` +
    `<h1>${have.length} / ${all.length} lines (${VOICE})</h1><table>${rows.join('')}</table>`);
  return have.length;
}

async function main(): Promise<void> {
  const all = allSpokenTexts();
  const todo = all.filter((s) => !existsSync(join(AUDIO_DIR, fileOf(s))));
  const chars = todo.reduce((n, s) => n + speakable(s.text).length, 0);
  console.log(`${all.length} spoken lines, ${todo.length} without audio (${chars} characters), voice ${VOICE}`);
  if (flag('dry')) return;
  const { key, region } = credentials();
  if (!key || !region) {
    console.error('No Azure Speech key. Set AZURE_SPEECH_KEY and AZURE_SPEECH_REGION, or create .secrets/azure-speech.json (see docs/AUDIO.md).');
    process.exit(2);
  }
  mkdirSync(AUDIO_DIR, { recursive: true });
  const url = `https://${region}.tts.speech.microsoft.com/cognitiveservices/v1`;
  const queue = todo.slice(0, Number(opt('limit') ?? todo.length));
  let done = 0, failed = 0;
  const worker = async () => {
    for (let s = queue.shift(); s; s = queue.shift()) {
      try {
        writeFileSync(join(AUDIO_DIR, fileOf(s)), await synth(url, key, ssml(s)));
        done++;
        if (done % 50 === 0) console.log(`  ${done} done…`);
      } catch (e) {
        failed++;
        console.error(`  failed: ${s.text.slice(0, 40)} (${(e as Error).message})`);
      }
    }
  };
  await Promise.all(Array.from({ length: WORKERS }, worker));
  if (flag('prune')) {
    const keep = new Set(all.map(fileOf));
    for (const f of readdirSync(AUDIO_DIR)) if (f.endsWith('.mp3') && !keep.has(f)) unlinkSync(join(AUDIO_DIR, f));
  }
  const n = writeOutputs(all);
  console.log(`generated ${done}, failed ${failed}; ${n}/${all.length} lines have audio. Listen: test-results/audio-review.html`);
}

await main();
