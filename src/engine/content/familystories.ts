export const storiesFrom = (rows: Row[]): Story[] => rows.map((r) => {
  const marked = r.paras.flat().flatMap((t, i) => (t.startsWith('* ') ? [i] : []));
  const paragraphs = r.paras.map((p) => p.map((t) => nfc(t.replace(/^\* /, ''))));
  const sentences = paragraphs.flat();
  return {
    id: r.id,
    title: nfc(r.title),
    kind: 'read',
    level: levelForLength(sentences.length),
    paragraphs,
    questions: r.qs.map(([q, type, depth, opts], i) => {
      const k = (i + r.id.length) % opts.length;
      const shown = [...opts.slice(k), ...opts.slice(0, k)];
      return { q: nfc(q), type, depth, options: shown.map(([emoji, label]) => ({ emoji, label: nfc(label) })), answer: (opts.length - k) % opts.length };
    }),
    order: r.order ?? marked,
    words: sentences.flatMap((t) => textWords(t)),
    review: 'checked',
  } satisfies Story;
});

export const FAMILY_STORIES: Story[] = storiesFrom(ROWS);
